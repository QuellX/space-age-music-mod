# Copies the Space Age soundtrack from your installed game into this mod and (with -Install) packages it into
# the Factorio mods folder. The copied files are Wube's DLC assets: keep them on this PC, never publish them.
#
#   .\build.ps1            # copy music + track definitions into this folder
#   .\build.ps1 -Install   # ... and build sa-music-on-nauvis_<version>.zip in the mods folder (close Factorio first)
param(
  [string]$Game = 'E:\games\steam\steamapps\common\Factorio',
  [string]$ModsDir = 'E:\games\mods\Factorio',
  [switch]$Install
)
$ErrorActionPreference = 'Stop'
Add-Type -AssemblyName System.IO.Compression, System.IO.Compression.FileSystem

$mod = $PSScriptRoot
$info = Get-Content (Join-Path $mod 'info.json') -Raw | ConvertFrom-Json
$src = Join-Path $Game 'data\space-age'
if (-not (Test-Path "$src\sound\ambient")) { throw "Space Age music not found in $src. Is the Space Age DLC installed?" }
$saVersion = (Get-Content "$src\info.json" -Raw | ConvertFrom-Json).version
$utf8 = New-Object Text.UTF8Encoding($false)
function Rewrite([string]$from, [string]$to) {
  $text = [IO.File]::ReadAllText($from, $utf8).Replace('__space-age__/', "__$($info.name)__/")
  [IO.File]::WriteAllText($to, $text, $utf8)
}

# 1. Music files and layered-track scripts
$dest = Join-Path $mod 'sound\ambient'
if (Test-Path (Join-Path $mod 'sound')) { Remove-Item (Join-Path $mod 'sound') -Recurse -Force }
robocopy "$src\sound\ambient" $dest /E /NFL /NDL /NJH /NJS /NP | Out-Null
if ($LASTEXITCODE -ge 8) { throw "robocopy failed ($LASTEXITCODE)" }
$luas = Get-ChildItem $dest -Recurse -Filter *.lua
foreach ($f in $luas) { Rewrite $f.FullName $f.FullName }

# 2. Track list
Rewrite "$src\prototypes\ambient-sounds.lua" (Join-Path $mod 'ambient-sounds.lua')
[IO.File]::WriteAllText((Join-Path $dest 'check.lua'), "-- Generated by build.ps1 from Space Age $saVersion`nreturn true`n", $utf8)

$oggs = Get-ChildItem $dest -Recurse -Filter *.ogg
'copied {0} music files ({1:N0} MB) and {2} track scripts from Space Age {3}' -f $oggs.Count, (($oggs | Measure-Object Length -Sum).Sum / 1MB), $luas.Count, $saVersion

if (-not $Install) { exit 0 }

# 3. Package
$top = "$($info.name)_$($info.version)"
$zipPath = Join-Path $ModsDir "$top.zip"
if (Test-Path $zipPath) { Remove-Item $zipPath -Force }
$zip = [IO.Compression.ZipFile]::Open($zipPath, [IO.Compression.ZipArchiveMode]::Create)
try {
  foreach ($item in 'info.json', 'settings.lua', 'data.lua', 'data-final-fixes.lua', 'control.lua', 'ambient-sounds.lua', 'locale', 'sound') {
    $path = Join-Path $mod $item
    $files = if (Test-Path $path -PathType Container) { Get-ChildItem $path -Recurse -File } else { Get-Item $path }
    foreach ($f in $files) {
      $rel = $f.FullName.Substring($mod.Length + 1) -replace '\\', '/'
      $level = if ($f.Extension -eq '.ogg') { [IO.Compression.CompressionLevel]::NoCompression } else { [IO.Compression.CompressionLevel]::Optimal }
      [void][IO.Compression.ZipFileExtensions]::CreateEntryFromFile($zip, $f.FullName, "$top/$rel", $level)
    }
  }
} finally { $zip.Dispose() }
'installed {0} ({1:N0} MB)' -f $zipPath, ((Get-Item $zipPath).Length / 1MB)
# Older versions: a running game locks its zip, so only warn (Factorio loads the highest version anyway).
foreach ($old in Get-ChildItem $ModsDir -Filter "$($info.name)_*.zip" | Where-Object { $_.FullName -ne $zipPath }) {
  try { Remove-Item $old.FullName -Force -ErrorAction Stop; "removed old $($old.Name)" } catch { "WARNING: $($old.Name) is locked (game running?); delete it after closing Factorio" }
}
exit 0
